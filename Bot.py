COMBO = {3: "🔥 КОМБО x3! Разогнался!", 5: "⚡ КОМБО x5! Ты в потоке!", 8: "💎 КОМБО x8! Тебя не остановить!", 12: "👑 КОМБО x12! Легенда трассы!"}

