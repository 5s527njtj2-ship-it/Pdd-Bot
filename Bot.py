def load():
    try:
        with open(DB_FILE, encoding="utf-8") as f: return json.load(f)
    except Exception: return {}
DB = load()
def save():
    with open(DB_FILE, "w", encoding="utf-8") as f: json.dump(DB, f, ensure_ascii=False)
def user(uid):
    return DB.setdefault(str(uid), {"xp": 0, "ok": 0, "bad": 0, "wrong": [], "seen": [], "best": 0, "streak": 0, "day": ""})
def level(xp):
    i = 0
    for k, (need, _) in enumerate(LEVELS):
        if xp >= need: i = k
    return i
def bar(p, n=10):
    f = round(p * n); return "▰" * f + "▱" * (n - f)

# ───────────────────────── ЭКРАНЫ ─────────────────────────
def menu_kb():
    return M([[B("⚡ Быстрый раунд (5)", callback_data="m:quick"), B("⏱ Блиц (10)", callback_data="m:blitz")],
              [B("💀 Выживание (3 жизни)", callback_data="m:surv")],
              [B("🎯 По темам", callback_data="m:topics"), B("🧠 Работа над ошибками", callback_data="m:fix")],
              [B("📊 Мой профиль", callback_data="m:me")]])

async def start(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    u = user(update.effective_user.id); save()
    await update.message.reply_text(
        f"🚗 ПДД-КВЕСТ\n\nТвой ранг: {LEVELS[level(u['xp'])][1]}  ·  {u['xp']} XP\n\n"
        "Отвечай, копи XP, собирай комбо 🔥, качай ранг до Магистра ПДД.\n"
        "Ошибки сами падают в «Работу над ошибками» — прогоняй их, пока не исчезнут.\n\nПогнали? 👇",
        reply_markup=menu_kb())

def profile_text(u):
    lv = level(u["xp"]); name = LEVELS[lv][1]
    if lv + 1 < len(LEVELS):
        a, b = LEVELS[lv][0], LEVELS[lv + 1][0]
        nxt = f"{bar((u['xp'] - a) / (b - a))}  до «{LEVELS[lv + 1][1]}» ещё {b - u['xp']} XP"
    else: nxt = "👑 Максимальный ранг!"
    tot = u["ok"] + u["bad"]; acc = round(100 * u["ok"] / tot) if tot else 0
    return (f"📊 ПРОФИЛЬ\n\n{name}\n{u['xp']} XP\n{nxt}\n\n"
            f"🎯 Точность: {acc}% ({u['ok']}/{tot})\n📚 Изучено вопросов: {len(u['seen'])}/{len(Q)}\n"
            f"🔥 Дней подряд: {u['streak']}\n💀 Рекорд выживания: {u['best']}\n🧠 Ошибок на отработку: {len(u['wrong'])}")

