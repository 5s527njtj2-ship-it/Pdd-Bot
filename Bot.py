async def start_game(chat, ctx, uid, mode, topic=None):
    u = user(uid); idx = list(range(len(Q)))
    if mode == "quick":
        unseen = [i for i in idx if i not in u["seen"]]; random.shuffle(unseen)
        pool = (unseen + random.sample(idx, len(idx)))[:5]
    elif mode == "blitz": pool = random.sample(idx, 10)
    elif mode == "surv": pool = random.sample(idx, len(idx))
    elif mode == "fix":
        pool = list(u["wrong"]); random.shuffle(pool)
        if not pool:
            await ctx.bot.send_message(chat, "🧠 Ошибок нет — ты чист, как новый техпаспорт ✨", reply_markup=menu_kb()); return
        pool = pool[:10]
    else:
        pool = [i for i in idx if Q[i][0] == topic]; random.shuffle(pool)
    ctx.user_data["s"] = {"mode": mode, "queue": pool, "i": 0, "score": 0, "combo": 0, "maxc": 0,
                          "lives": 3, "xp": 0, "lv0": level(u["xp"]), "nonce": None, "uid": uid}
    intro = {"quick": "⚡ 5 вопросов. Поехали!", "blitz": "⏱ БЛИЦ! Ответ быстрее 8 сек = +10 XP бонус",
             "surv": "💀 ВЫЖИВАНИЕ. 3 жизни. Сколько протянешь?", "fix": "🧠 Добиваем ошибки. Верный ответ убирает вопрос из списка.",
             "topic": f"🎯 Тема: {topic}"}[mode]
    await ctx.bot.send_message(chat, intro)
    await send_q(chat, ctx)

async def send_q(chat, ctx):
    s = ctx.user_data.get("s")
    if not s: return
    if s["i"] >= len(s["queue"]) or s["lives"] <= 0:
        return await finish(chat, ctx)
    qi = s["queue"][s["i"]]; topic, text, opts, _ = Q[qi]
    order = random.sample(range(4), 4); s["order"] = order
    s["nonce"] = str(random.randint(1000, 9999)); s["t"] = time.time()
    if s["mode"] == "surv": head = "❤️" * s["lives"] + "🖤" * (3 - s["lives"]) + f"   Счёт: {s['score']}"
    else: head = f"Вопрос {s['i'] + 1}/{len(s['queue'])}"
    if s["combo"] >= 2: head += f"   🔥x{s['combo']}"
    nums = ["1️⃣", "2️⃣", "3️⃣", "4️⃣"]
    body = "\n".join(f"{nums[k]} {opts[o]}" for k, o in enumerate(order))
    kb = M([[B(nums[k], callback_data=f"a:{s['nonce']}:{k}") for k in range(4)]])
    await ctx.bot.send_message(chat, f"{head}\n{topic}\n\n❓ {text}\n\n{body}", reply_markup=kb)

def touch_day(u):
    today = date.today().isoformat()
    if u["day"] != today:
        u["streak"] = u["streak"] + 1 if u["day"] == (date.today() - timedelta(days=1)).isoformat() else 1
        u["day"] = today

async def on_answer(q, ctx, nonce, k):
    s = ctx.user_data.get("s")
    if not s or s.get("nonce") != nonce:
        return await q.answer("Уже отвечено 🙂")
    await q.answer(); s["nonce"] = None
    u = user(q.from_user.id); touch_day(u)
    qi = s["queue"][s["i"]]; _, text, opts, expl = Q[qi]
    if qi not in u["seen"]: u["seen"].append(qi)
    ok = s["order"][k] == 0; el = time.time() - s["t"]
    old = q.message.text
    if ok:
        gain = 10 + min(s["combo"], 5) * 2
        if s["mode"] == "blitz" and el < 8: gain += 10
        s["combo"] += 1; s["maxc"] = max(s["maxc"], s["combo"]); s["score"] += 1; s["xp"] += gain
        u["xp"] += gain; u["ok"] += 1
        if qi in u["wrong"]: u["wrong"].remove(qi)
        extra = f"\n{COMBO[s['combo']]}" if s["combo"] in COMBO else ""
        speed = " ⚡+10 за скорость" if s["mode"] == "blitz" and el < 8 else ""
        await q.edit_message_text(f"{old}\n\n✅ {random.choice(HYPE)} +{gain} XP{speed}{extra}\n💡 {expl}")
        s["i"] += 1; save()
        await send_q(q.message.chat_id, ctx)
    else:
        s["combo"] = 0; u["bad"] += 1
        if qi not in u["wrong"]: u["wrong"].append(qi)
        if s["mode"] == "surv": s["lives"] -= 1
        s["i"] += 1; save()
        lives = ""
        if s["mode"] == "surv":
            lives = "\n💔 Минус жизнь!" if s["lives"] > 0 else "\n☠️ Жизни кончились!"
        btn = "📋 Итоги" if (s["mode"] == "surv" and s["lives"] <= 0) or s["i"] >= len(s["queue"]) else "👌 Понял, дальше"
        await q.edit_message_text(f"{old}\n\n❌ Мимо. Правильно: «{opts[0]}»\n💡 {expl}{lives}",
                                  reply_markup=M([[B(btn, callback_data="n")]]))

async def finish(chat, ctx):
    s = ctx.user_data.pop("s", None)
    if not s: return
    u = user(s["uid"])
    n = len(s["queue"]) if s["mode"] != "surv" else s["score"]
    if s["mode"] == "surv":
        new_rec = s["score"] > u["best"]; u["best"] = max(u["best"], s["score"])
        res = f"💀 Выжил {s['score']} вопросов" + ("\n🏆 НОВЫЙ РЕКОРД!" if new_rec else f"\nРекорд: {u['best']}")
    else:
        pct = s["score"] / max(n, 1)
        mood = "🏆 Идеально! Инспектор аплодирует" if pct == 1 else "😎 Хорошо идёшь" if pct >= .7 else "🛠 Есть над чем поработать — ошибки уже в списке"
        res = f"Результат: {s['score']}/{n}\n{mood}"
    lv = level(u["xp"]); up = f"\n\n🎉 НОВЫЙ РАНГ: {LEVELS[lv][1]}!" if lv > s["lv0"] else ""
    save()
    await ctx.bot.send_message(chat, f"🏁 ФИНИШ\n\n{res}\n+{s['xp']} XP · макс. комбо {s['maxc']}{up}\n\n"
                                     f"Ещё разок? Пять вопросов — это 1 минута 😉", reply_markup=menu_kb())

async def on_cb(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    q = update.callback_query; d = q.data; chat = q.message.chat_id; uid = q.from_user.id
    if d.startswith("a:"):
        _, nonce, k = d.split(":"); return await on_answer(q, ctx, nonce, int(k))
    await q.answer()
    if d == "n":
        await q.edit_message_reply_markup(None); return await send_q(chat, ctx)
    if d == "m:topics":
        rows = [[B(t, callback_data=f"t:{i}")] for i, t in enumerate(TOPICS)] + [[B("⬅️ Меню", callback_data="m:menu")]]
        return await q.edit_message_text("🎯 Выбери тему:", reply_markup=M(rows))
    if d.startswith("t:"):
        return await start_game(chat, ctx, uid, "topic", TOPICS[int(d[2:])])
    if d == "m:me":
        return await q.edit_message_text(profile_text(user(uid)), reply_markup=M([[B("⬅️ Меню", callback_data="m:menu")]]))
    if d == "m:menu":
        u = user(uid)
        return await q.edit_message_text(f"🚗 ПДД-КВЕСТ · {LEVELS[level(u['xp'])][1]} · {u['xp']} XP", reply_markup=menu_kb())
    if d.startswith("m:"):
        return await start_game(chat, ctx, uid, d[2:])

async def me(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(profile_text(user(update.effective_user.id)), reply_markup=menu_kb())

def main():
    app = Application.builder().token(TOKEN).build()
    app.add_handler(CommandHandler(["start", "menu"], start))
    app.add_handler(CommandHandler("me", me))
    app.add_handler(CallbackQueryHandler(on_cb))
    print("Бот запущен 🚗"); app.run_polling()

if __name__ == "__main__":
    main()
